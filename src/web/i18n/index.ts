const savedLanguage = localStorage.getItem("opensublists-language");
const detectedLanguage = navigator.language.toLowerCase().startsWith("zh") ? "zh-Hans" : "en";

void i18n.use(initReactI18next).init({
  resources: { en, "zh-Hans": zhHans },
  lng: savedLanguage ?? detectedLanguage,
  fallbackLng: "en",
  interpolation: { escapeValue: false },
  returnNull: false,
});

export async function setLanguage(language: "en" | "zh-Hans") {
  localStorage.setItem("opensublists-language", language);
  await i18n.changeLanguage(language);
  document.documentElement.lang = language;
}

document.documentElement.lang = i18n.language;

